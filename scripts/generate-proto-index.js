#!/usr/bin/env node
// generate-proto-index.js — после `buf generate` пишет src/proto-generated/index.ts
// (баррел), который реэкспортирует ВСЕ сгенерированные символы из всех _pb.ts
// (и _pb.d.ts, если кто-когда генерит .d.ts).
//
// Почему баррел: код в src/ импортирует `import { Envelope } from './proto-generated'`,
// а не `import { Envelope } from './proto-generated/common/v1/envelope_pb'` —
// путь до конкретного файла может смениться, баррел стабилен.
//
// Как работает:
//  1. Находит src/proto-generated (relative to repo root).
//  2. Рекурсивно обходит, собирает *.ts (кроме *.d.ts и index.ts).
//  3. Для каждого — relative ESM-import path + `export * from`.
//  4. Сортирует по алфавиту (детерминистичный вывод) и пишет index.ts.
//
// Без внешних зависимостей.

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const outDir = path.join(repoRoot, 'src', 'proto-generated');

if (!fs.existsSync(outDir)) {
  console.error(`[generate-proto-index] ${path.relative(repoRoot, outDir)} not found; run 'buf generate' first.`);
  process.exit(1);
}

/** Recursively collect *.ts (excluding *.d.ts and index.ts) under a directory. */
function collectTs(dir, acc = []) {
  for (const name of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, name.name);
    if (name.isDirectory()) {
      collectTs(full, acc);
    } else if (name.isFile() && name.name.endsWith('.ts') && !name.name.endsWith('.d.ts') && name.name !== 'index.ts') {
      acc.push(full);
    }
  }
  return acc;
}

const files = collectTs(outDir).sort();
if (files.length === 0) {
  console.warn(`[generate-proto-index] no .ts files found under ${path.relative(repoRoot, outDir)}; nothing to export.`);
}

const lines = [
  '// index.ts — GENERATED by scripts/generate-proto-index.js (do not edit manually).',
  '// Re-exports all protobuf-es generated symbols from all _pb.ts modules.',
  '',
  '// eslint-disable-next-line import/no-internal-modules',
];

for (const file of files) {
  // .ts → .js: orthodox ESM pattern (tsc resolves .js → .ts; dist runs natively on Node).
  const rel = path.relative(outDir, file).replace(/\.ts$/i, '.js').replace(/\\/g, '/');
  lines.push(`export * from ${JSON.stringify(`./${rel}`)};`);
}

lines.push('');
const out = lines.join('\n');
fs.writeFileSync(path.join(outDir, 'index.ts'), out, { encoding: 'utf-8' });

console.log(`[generate-proto-index] wrote ${files.length ? `${files.length} export(s) ` : ''}to ${path.relative(repoRoot, path.join(outDir, 'index.ts'))}`);
